"""Generate the Ultralytics data.yaml for a prepared dataset."""
from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml


def build_data_config(dataset_dir: Path, class_names: list[str]) -> dict[str, Any]:
    """data.yaml content with absolute paths (forward slashes work on every OS)."""
    root = Path(dataset_dir).resolve()
    names = [n.strip() for n in class_names]
    if not names or any(not n for n in names):
        raise ValueError("Every class needs a non-empty name.")
    return {
        "path": root.as_posix(),
        "train": (root / "images" / "train").as_posix(),
        "val": (root / "images" / "val").as_posix(),
        "nc": len(names),
        "names": {i: n for i, n in enumerate(names)},
    }


def write_data_yaml(yaml_path: Path, dataset_dir: Path, class_names: list[str]) -> Path:
    config = build_data_config(dataset_dir, class_names)
    yaml_path = Path(yaml_path)
    yaml_path.parent.mkdir(parents=True, exist_ok=True)
    header = "# Generated by LocalTrainer. Edit class names in the app, not here.\n"
    yaml_path.write_text(header + yaml.safe_dump(config, sort_keys=False, allow_unicode=True), encoding="utf-8")
    return yaml_path


def read_data_yaml(yaml_path: Path) -> dict[str, Any]:
    return yaml.safe_load(Path(yaml_path).read_text(encoding="utf-8")) or {}
